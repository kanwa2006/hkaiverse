"""Net-time-saved arithmetic. ALL INPUTS ARE ASSUMPTIONS (nothing measured). Writes ../evidence/roi_results.md"""
from pathlib import Path
S = {  # name: (cases/month, current min/case, proposed min/case, monthly overhead min)
    "Conservative": (50, 8, 5, 180),
    "Base (report example)": (100, 10, 4, 180),
    "Optimistic": (200, 12, 3, 180),
}
out = ["# Net time saved - generated by roi_calc.py (assumptions, not measurements)", "",
       "| Scenario | Cases/mo | Current min/case | Proposed min/case | Overhead min/mo | Gross saving (min) | Net saving (min) | Net (h/mo) | Break-even cases/mo |", "|---|---|---|---|---|---|---|---|---|"]
for n, (v, c, p, o) in S.items():
    g = v * (c - p); net = g - o
    out.append(f"| {n} | {v} | {c} | {p} | {o} | {g} | {net} | {net/60:.1f} | {o/(c-p):.0f} |")
out += ["", "Payback (months) = one-time build + training hours / net hours per month; one-time effort is not measured, so no payback figure is claimed."]
Path(__file__).resolve().parent.parent.joinpath("evidence", "roi_results.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
